let fruits=['apple','banana','grapes']
//remove last variable
fruits.pop()
//adds a variable at last
fruits.push('mango')
//adds variable at first
fruits.unshift('orange')
//remove variable at first
fruits.shift()
//sort the array
fruits.sort()
//finds the index of given object
console.log(fruits.indexOf('mango'))
console.log(fruits.indexOf('grapes'))
//prints the length of an array
console.log(fruits.length)
console.log(fruits)
